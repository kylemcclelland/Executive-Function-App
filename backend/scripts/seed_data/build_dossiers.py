#!/usr/bin/env python
# ruff: noqa: E501
"""Write docs/devotion-dossiers.md: one reviewable source dossier per devotion, derived from the seed data.

    python backend/scripts/seed_data/build_dossiers.py

It reads the draft definitions and prayer_sources.json and prints NO prayer wording: only where each text
came from, its rights, and what is still unresolved. Nothing here is verified, approved or published.
"""

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent))
sys.path.insert(0, str(HERE.parents[1]))
import devotion_drafts  # noqa: E402

CODES = [f"DEV-00{n}" for n in range(1, 8)]
OUT = HERE.parents[2] / "docs" / "devotion-dossiers.md"
RIGHTS = {
    "public_domain": "Public domain (US)", "restricted": "RESTRICTED: reproduction not cleared; wording withheld",
    "unverified": "Not yet checked", "licensed": "Licensed", "permission_granted": "Permission granted",
}
LANGUAGES = {"en": "English", "la": "Latin"}


def questions(item: dict, texts: dict) -> list[str]:
    out = []
    for code, name in LANGUAGES.items():
        t = texts.get(code)
        if t is None:
            out.append(f"{name}: no source has been identified, so no record exists.")
        elif not t["body"]:
            out.append(f"{name}: wording withheld ({RIGHTS[t['license_status']].split(':')[0].lower()}). Needs written permission from {t['source_authority']} or a cleared alternative source before any wording can be held, verified or approved.")
        elif t["source_title"] == "User-supplied Latin text":
            out.append(f"{name}: user-supplied text. The file names no source, edition or rights: record where it comes from and its reproduction rights before it can be verified. Review the listed observations (nothing was changed).")
        else:
            out.append(f"{name}: compare the wording with its source link, and decide whether this edition ({t['source_edition']}) is the form you want.")
            if t["is_translation"]:
                out.append(f"{name}: {t['translator']}. Decide whether that attribution is acceptable.")
    notes = {
        "apostles-creed": "English: the source prints no comma after “Holy Ghost” in the third article, exactly as copied. Decide whether to keep it as sourced.",
        "the-angelus": "English: this edition abbreviates each Hail Mary and has no versicle/response labels. A better bilingual public-domain edition (1888 Manual of Prayers) needs a proofread transcription.",
        "sign-of-the-cross": "Latin: taken from the rubric where the priest begins the Mass, not from a stand-alone prayer text.",
    }
    if item["slug"] in notes:
        out.append(notes[item["slug"]])
    out.append("Prose: verify every citation marked “to be verified”, and approve, correct or replace the AI-drafted introduction, purpose and occasions.")
    return out


def merge(sources):
    import seed_devotion_drafts
    return seed_devotion_drafts.merge_user_supplied(list(sources))


def main() -> None:
    sources = json.loads((HERE / "prayer_sources.json").read_text(encoding="utf-8"))["texts"]
    lines = [
        "# Foundational devotions: editorial source dossiers (DEV-001 to DEV-007)", "",
        "**Everything below is a draft for your review. Nothing is verified, approved or published.** The introductions, purposes and occasions are "
        "**unapproved editorial prose drafted with AI assistance**: they are not official Church texts and not quotations. No prayer wording appears "
        "in this document: wording, where held, is in the database/seed data with its source, and is never AI-written or AI-translated. "
        "English and Latin are separate texts with separate sources, rights and approvals.", "",
        "Generated by `backend/scripts/seed_data/build_dossiers.py` from the seed data. See `docs/devotion-source-research.md` for how sources and rights were checked.", "",
        "| ID | Devotion | Category | English | Latin | Status |", "|---|---|---|---|---|---|",
    ]
    rows, blocks = [], []
    for item in (d for d in devotion_drafts.DRAFTS if d["code"] in CODES):
        texts = {t["language"]: t for t in merge(sources) if t["devotion_slug"] == item["slug"] and t["slot"] == "main"}

        def state(code):
            t = texts.get(code)
            return "no record" if t is None else ("wording held" if t["body"] else "citation only")
        rows.append(f"| {item['code']} | {item['title']} | {item['category']} | {state('en')} | {state('la')} | Proposed: not verified, not approved |")
        usage = next((i.split(": ", 1)[1] for i in item["instructions"] if i.startswith("Traditional occasions:")), "")
        b = [f"## {item['code']}: {item['title']}", "", f"**Category:** {item['category']}  ·  **Workflow status:** proposed (unpublished)  ·  **Prose:** AI-drafted, unapproved", "",
             f"**Short description:** {item['subtitle']}", "", f"**Overview (unapproved):** {item['overview']}", "",
             f"**Historical introduction (unapproved):** {item['background']}", "", f"**Devotional purpose (unapproved):** {item['significance']}", "",
             f"**Traditional usage (unapproved):** {usage}", "", "**References for the prose:**"]
        b += [f"- {r['label']}" + (f" <{r['url']}>" if r["url"] else "") for r in item["references"]]
        b += ["", "### Prayer texts: English and Latin are separate", "", "| | English | Latin |", "|---|---|---|"]
        for label, key in (("Source title", "source_title"), ("Issuing authority", "source_authority"), ("Edition", "source_edition"), ("Published", "source_date"), ("Link", "source_url")):
            b.append(f"| {label} | " + " | ".join((texts.get(c) or {}).get(key) or "—" for c in LANGUAGES) + " |")
        b.append("| Translator | " + " | ".join(((texts.get(c) or {}).get("translator") or ("n/a (not a translation)" if texts.get(c) and not texts[c]["is_translation"] else "—")) for c in LANGUAGES) + " |")
        b.append("| Reproduction rights | " + " | ".join(RIGHTS.get((texts.get(c) or {}).get("license_status"), "—") for c in LANGUAGES) + " |")
        b.append("| Wording | " + " | ".join(state(c) for c in LANGUAGES) + " |")
        b.append("| Source verification | Not verified | Not verified |")
        b.append("| Approval | Not approved | Not approved |")
        b += ["", "**Outstanding editorial questions:**"] + [f"- {q}" for q in questions(item, texts)] + [""]
        blocks.append("\n".join(b))
    OUT.write_text("\n".join(lines + rows + [""] + blocks) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
